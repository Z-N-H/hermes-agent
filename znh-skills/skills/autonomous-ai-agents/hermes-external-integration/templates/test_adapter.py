from agent_context.hermes_agent import HermesAgent


def _fake_completed_process(
    *, returncode: int = 0, stdout: str = "", stderr: str = ""
) -> subprocess.CompletedProcess:
    return subprocess.CompletedProcess(
        args=["guest"], returncode=returncode, stdout=stdout, stderr=stderr
    )


def _make_agent() -> HermesAgent:
    return HermesAgent(name="Test Agent", max_turns=5)


