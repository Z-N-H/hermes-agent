@pytest.mark.anyio
async def test_different_sessions_do_not_cross_bleed():
    agent = _make_agent()
    fake_a = _fake_completed_process(stdout="a", stderr="session_id: s-a\n")
    fake_b = _fake_completed_process(stdout="b", stderr="session_id: s-b\n")

    with patch("agent_context.hermes_agent.subprocess.run", return_value=fake_a):
        await agent._arun_adapter("hi", session_id="agno-a")
    with patch("agent_context.hermes_agent.subprocess.run", return_value=fake_b):
        await agent._arun_adapter("hi", session_id="agno-b")

    assert agent._hermes_session_ids["agno-a"] == "s-a"
    assert agent._hermes_session_ids["agno-b"] == "s-b"


